# Figure 5: latency
# --------------------------------------------------------------------------
def figure_latency(rows) -> None:
    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(7.0, 2.7))
    qs = [0.1, 0.25, 0.5, 0.75, 0.9, 0.95, 0.99, 0.999]
    labels = ["p10", "p25", "p50", "p75", "p90", "p95", "p99", "p99.9"]
    for key, colour, label, marker in [
        ("ours_ms", OURS, "NMAFC", "o"),
        ("rag_ms", ACCENT, "RAG baseline", "s"),
    ]:
        vals = [r[key] for r in rows if r.get(key)]
        ax.plot(range(len(qs)), [quantile(vals, q) / 1000 for q in qs],
                marker=marker, color=colour, markersize=4, linewidth=1.1,
                label=label)
        ax2.hist([min(v / 1000, 10) for v in vals], bins=50,
                 histtype="step", linewidth=1.0, color=colour, label=label)
    ax.set_yscale("log")
    ax.set_xticks(range(len(qs)))
    ax.set_xticklabels(labels, rotation=45)
    ax.set_ylabel("end to end latency (s, log)")
    ax.legend(loc="upper left")
    ax.spines[["top", "right"]].set_visible(False)
    ax.set_title("percentiles")
    ax2.set_xlabel("latency (s, clipped at 10)")
    ax2.set_ylabel("questions")
    ax2.spines[["top", "right"]].set_visible(False)
    ax2.set_title("distribution")
    save(fig, "fig5_latency")


