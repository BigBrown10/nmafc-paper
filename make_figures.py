# Figure 4: accuracy against context spend
# --------------------------------------------------------------------------
def figure_pareto(rows) -> None:
    ship = {r["question"]: r for r in load("od_ship")}
    points = []
    for name, label in [("od_ship", "facts only (shipped)"),
                        ("od_ground", "facts plus grounding"),
                        ("od_wide", "facts plus wide hydration")]:
        arm = load(name)
        acc = 100 * sum(r["ok"] for r in arm) / len(arm)
        tokens = sum(r["chars"] for r in arm) / len(arm) / CHARS_PER_TOKEN
        points.append((tokens, acc, label))
    rag_rows = load("od_ship")
    rag_pt = (sum(r["rag_chars"] for r in rag_rows) / len(rag_rows)
              / CHARS_PER_TOKEN,
              100 * sum(r["rag_ok"] for r in rag_rows) / len(rag_rows))

    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(7.0, 2.9))

    ax.plot([p[0] for p in points], [p[1] for p in points], "-o",
            color=OURS, markersize=5, linewidth=1.1, zorder=3)
    for i, (x, y, label) in enumerate(points):
        ax.annotate(label, (x, y), textcoords="offset points",
                    xytext=(7, -3 if i == 0 else 7), ha="left",
                    fontsize=7, color=GREY)
    ax.plot(*rag_pt, "s", color=ACCENT, markersize=6, zorder=3)
    ax.annotate("RAG baseline", rag_pt, textcoords="offset points",
                xytext=(0, -14), ha="center", fontsize=7, color=ACCENT)
    ax.set_xlabel("mean retrieved context (tokens)")
    ax.set_ylabel("open-domain accuracy (%)")
    ax.set_xlim(880, 1640)
    ax.set_ylim(78.6, 82.4)
    ax.spines[["top", "right"]].set_visible(False)
    ax.set_title("open-domain: buying accuracy with context")

    by_cat = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(r)
    for cat in ORDER:
        subset = by_cat[cat]
        ot = sum(r["ours_chars"] for r in subset) / len(subset) / 4
        gt = sum(r["rag_chars"] for r in subset) / len(subset) / 4
        oa = 100 * sum(r["ours_ok"] for r in subset) / len(subset)
        ga = 100 * sum(r["rag_ok"] for r in subset) / len(subset)
        ax2.annotate("", xy=(ot, oa), xytext=(gt, ga),
                     arrowprops={"arrowstyle": "-|>", "linewidth": 0.8,
                                 "color": "#9aa5b4", "shrinkA": 3,
                                 "shrinkB": 3})
        ax2.plot(gt, ga, "s", color=RAG, markeredgecolor="#2b2b2b",
                 markeredgewidth=0.5, markersize=5.5)
        ax2.plot(ot, oa, "o", color=OURS, markersize=5.5)
        ax2.annotate(cat, (ot, oa), textcoords="offset points",
                     xytext=(8, 5), ha="left", fontsize=6.8, color=GREY)
    ax2.set_xlabel("mean retrieved context (tokens)")
    ax2.set_ylabel("accuracy (%)")
    ax2.set_xlim(880, 1640)
    ax2.spines[["top", "right"]].set_visible(False)
    ax2.set_title("per category: arrow runs RAG to NMAFC")
    save(fig, "fig4_accuracy_vs_context")


