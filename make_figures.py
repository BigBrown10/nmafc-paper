def load(name: str) -> list[dict]:
    return json.loads((DATA / f"{name}.json").read_text(encoding="utf-8"))


def save(fig, stem: str) -> None:
    for ext in ("pdf", "png"):
        fig.savefig(FIGS / f"{stem}.{ext}")
    plt.close(fig)
    print(f"  wrote figures/{stem}.pdf and .png")


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return 100 * (centre - half), 100 * (centre + half)


def mcnemar(rows, a: str, b: str) -> tuple[int, int, float]:
    x = sum(1 for r in rows if r[a] and not r[b])
    y = sum(1 for r in rows if r[b] and not r[a])
    n = x + y
    if n == 0:
        return x, y, 1.0
    tail = sum(math.comb(n, k) for k in range(min(x, y) + 1))
    return x, y, min(1.0, 2 * tail / 2 ** n)


def quantile(vals: list[float], q: float) -> float:
    o = sorted(vals)
    i = min(len(o) - 1, max(0, math.ceil(q * len(o)) - 1))
    return o[i]


def words(s: str) -> list[str]:
    return re.findall(r"[a-z0-9']+", (s or "").lower())


def token_f1(pred: str, gold: str) -> float:
    p, g = Counter(words(pred)), Counter(words(gold))
    if not p or not g:
        return 0.0
    overlap = sum((p & g).values())
    if not overlap:
        return 0.0
    prec, rec = overlap / sum(p.values()), overlap / sum(g.values())
    return 2 * prec * rec / (prec + rec)


