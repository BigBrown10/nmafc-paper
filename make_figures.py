# Figure 6: the lead as a function of how much wording the gold answer wants
# --------------------------------------------------------------------------
def figure_gold_length(rows) -> None:
    bins = [(1, 2, "1 to 2"), (3, 4, "3 to 4"), (5, 8, "5 to 8"),
            (9, 99, "9 or more")]
    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(7.0, 2.9))

    for subset_name, subset, colour, marker in [
        ("scored (4)", [r for r in rows if r["category"] in SCORED],
         OURS, "o"),
        ("all (5)", rows, ACCENT, "s"),
    ]:
        leads, ns = [], []
        for lo, hi, _ in bins:
            v = [r for r in subset if lo <= len(words(r["gold"])) <= hi]
            o = 100 * sum(r["ours_ok"] for r in v) / len(v)
            g = 100 * sum(r["rag_ok"] for r in v) / len(v)
            leads.append(o - g)
            ns.append(len(v))
        ax.plot(range(len(bins)), leads, marker=marker, color=colour,
                markersize=5, linewidth=1.2, label=subset_name)
        for i, (lead, n) in enumerate(zip(leads, ns)):
            ax.annotate(f"n={n}", (i, lead), textcoords="offset points",
                        xytext=(0, -13 if colour == ACCENT else 8),
                        ha="center", fontsize=6.6, color=colour)
    ax.axhline(0, color="#333333", linewidth=0.8)
    ax.set_xticks(range(len(bins)))
    ax.set_xticklabels([b[2] for b in bins])
    ax.set_xlabel("words in the reference answer")
    ax.set_ylabel("NMAFC lead over RAG (points)")
    ax.legend(loc="lower left")
    ax.spines[["top", "right"]].set_visible(False)
    ax.set_title("the lead shrinks as the answer gets wordier")

    by_cat = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(r)
    xs = list(range(len(ORDER)))
    ours = [sum(token_f1(r["ours_pred"], r["gold"]) for r in by_cat[c])
            / len(by_cat[c]) for c in ORDER]
    rag = [sum(token_f1(r["rag_pred"], r["gold"]) for r in by_cat[c])
           / len(by_cat[c]) for c in ORDER]
    ax2.bar([x - 0.18 for x in xs], ours, 0.36, color=OURS,
            edgecolor="#2b2b2b", linewidth=0.6, label="NMAFC")
    ax2.bar([x + 0.18 for x in xs], rag, 0.36, color=RAG, hatch="///",
            edgecolor="#2b2b2b", linewidth=0.6, label="RAG baseline")
    ax2.set_xticks(xs)
    ax2.set_xticklabels(ORDER, rotation=20, ha="right")
    ax2.set_ylabel("token F1 against the reference")
    ax2.set_ylim(0, 0.82)
    ax2.legend(loc="upper left", ncol=2)
    ax2.spines[["top", "right"]].set_visible(False)
    ax2.set_title("wording overlap with the reference")
    save(fig, "fig6_gold_length")


