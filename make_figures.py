# Figure 2: per-category accuracy with Wilson intervals
# --------------------------------------------------------------------------
def figure_accuracy(rows) -> None:
    by_cat = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(r)
    groups = list(ORDER) + ["scored (4)", "all (5)"]
    sets = [by_cat[c] for c in ORDER]
    sets.append([r for r in rows if r["category"] in SCORED])
    sets.append(rows)

    fig, ax = plt.subplots(figsize=(7.0, 3.1))
    xs = list(range(len(groups)))
    width = 0.36
    for offset, key, colour, label, hatch in [
        (-width / 2, "ours_ok", OURS, "NMAFC", None),
        (width / 2, "rag_ok", RAG, "RAG baseline", "///"),
    ]:
        heights, errs = [], [[], []]
        for subset in sets:
            k, n = sum(r[key] for r in subset), len(subset)
            acc = 100 * k / n
            lo, hi = wilson(k, n)
            heights.append(acc)
            errs[0].append(acc - lo)
            errs[1].append(hi - acc)
        ax.bar([x + offset for x in xs], heights, width, label=label,
               color=colour, edgecolor="#2b2b2b", linewidth=0.6,
               hatch=hatch, yerr=errs, capsize=2.2,
               error_kw={"linewidth": 0.7, "ecolor": "#2b2b2b"})

    for i, subset in enumerate(sets):
        o = 100 * sum(r["ours_ok"] for r in subset) / len(subset)
        g = 100 * sum(r["rag_ok"] for r in subset) / len(subset)
        _, _, p = mcnemar(subset, "ours_ok", "rag_ok")
        stars = ("***" if p < 1e-3 else "**" if p < 1e-2
                 else "*" if p < 0.05 else "n.s.")
        ax.text(i, max(o, g) + 6.2, f"{o - g:+.1f}\n{stars}", ha="center",
                fontsize=7.2, color=ACCENT if o > g else GREY)

    ax.set_xticks(xs)
    ax.set_xticklabels([f"{g}\nn={len(s)}" for g, s in zip(groups, sets)])
    ax.set_ylabel("judged correct (%)")
    ax.set_ylim(0, 100)
    ax.axvline(4.5, color="#cccccc", linewidth=0.8, linestyle=":")
    ax.legend(loc="upper left", ncol=2)
    ax.spines[["top", "right"]].set_visible(False)
    save(fig, "fig2_accuracy_by_category")


# --------------------------------------------------------------------------
# Figure 3: discordant pairs, which is what McNemar actually tests
# --------------------------------------------------------------------------
def figure_discordance(rows) -> None:
    by_cat = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(r)
    fig, ax = plt.subplots(figsize=(7.0, 2.6))
    ys = list(range(len(ORDER)))[::-1]
    for y, cat in zip(ys, ORDER):
        subset = by_cat[cat]
        won, lost, p = mcnemar(subset, "ours_ok", "rag_ok")
        both = sum(1 for r in subset if r["ours_ok"] and r["rag_ok"])
        neither = sum(1 for r in subset
                      if not r["ours_ok"] and not r["rag_ok"])
        ax.barh(y, won, height=0.5, color=OURS, edgecolor="#2b2b2b",
                linewidth=0.6)
        ax.barh(y, -lost, height=0.5, color=RAG, edgecolor="#2b2b2b",
                linewidth=0.6, hatch="///")
        ax.text(won + 4, y, f"{won}", va="center", fontsize=7.6,
                color=OURS)
        ax.text(-lost - 4, y, f"{lost}", va="center", ha="right",
                fontsize=7.6, color="#4a5568")
        ax.text(128, y, f"agree {both + neither}   p={p:.3g}", va="center",
                fontsize=7.2, color=GREY)
    ax.axvline(0, color="#333333", linewidth=0.9)
    ax.set_yticks(ys)
    ax.set_yticklabels(list(ORDER))
    ax.set_xlim(-120, 205)
    ax.set_xlabel("discordant questions (left: only RAG correct,   "
                  "right: only NMAFC correct)")
    ax.spines[["top", "right", "left"]].set_visible(False)
    ax.tick_params(axis="y", length=0)
    save(fig, "fig3_discordance")


